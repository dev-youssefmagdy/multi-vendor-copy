import 'dart:convert';
import 'dart:io';

import 'package:path/path.dart' as p;

import '../images.dart';
import '../model.dart';
import 'plist.dart';

/// Tenant-specific iOS files, as paths relative to the Flutter project root.
/// They are laid over a snapshot of the project in an isolated build
/// workspace (see ios_workspace.dart); the shared working tree is never
/// changed, so its `ios/Flutter/AppIdentity.xcconfig` stays the `platform` app.
///
/// One `Runner` scheme and the existing Debug/Release/Profile configurations
/// are used for every tenant (no per-tenant schemes, no project.pbxproj edits):
///  * `ios/Flutter/AppIdentity.xcconfig`   bundle id, display name, link domain,
///    URL scheme, DEVELOPMENT_TEAM (included by Debug.xcconfig + Release.xcconfig;
///    the Runner target's build settings reference `$(APP_BUNDLE_ID)`).
///  * `ios/Flutter/TenantSigning.xcconfig` + `ios/Flutter/Release.xcconfig`
///    manual App Store signing with the tenant's fastlane-match profile
///    (Release/Profile only, so debug runs keep automatic signing).
///  * `ios/Runner/Runner.entitlements`     associated domains of this tenant only
///    (+ aps-environment when push is on).
///  * `ios/Runner/Assets.xcassets/AppIcon.appiconset/` from `branding.appIcon`
///    (the `platform` app keeps the committed icon set).
///  * `ios/Runner/GoogleService-Info.plist` only when push is enabled.
///  * `ExportOptions.plist` (workspace root) for `flutter build ipa`.
const iosAppIconSetDir = 'ios/Runner/Assets.xcassets/AppIcon.appiconset';

/// The AppIcon set Flutter's iOS template uses (same file names and slots as
/// the committed set; every size rendered from the tenant's 1024 icon).
const iosIconSlots = <(String size, String idiom, int scale)>[
  ('20x20', 'iphone', 2),
  ('20x20', 'iphone', 3),
  ('29x29', 'iphone', 1),
  ('29x29', 'iphone', 2),
  ('29x29', 'iphone', 3),
  ('40x40', 'iphone', 2),
  ('40x40', 'iphone', 3),
  ('60x60', 'iphone', 2),
  ('60x60', 'iphone', 3),
  ('20x20', 'ipad', 1),
  ('20x20', 'ipad', 2),
  ('29x29', 'ipad', 1),
  ('29x29', 'ipad', 2),
  ('40x40', 'ipad', 1),
  ('40x40', 'ipad', 2),
  ('76x76', 'ipad', 1),
  ('76x76', 'ipad', 2),
  ('83.5x83.5', 'ipad', 2),
  ('1024x1024', 'ios-marketing', 1),
];

String _iconFile(String size, int scale) => 'Icon-App-$size@${scale}x.png';

int _iconPixels(String size, int scale) =>
    (double.parse(size.split('x').first) * scale).round();

/// Provisioning profile name created by `fastlane match appstore`.
String matchProfileName(String bundleId) => 'match AppStore $bundleId';

/// Universal Links domains of [t] (without the `applinks:` prefix).
List<String> iosAssociatedDomains(TenantManifest t, Registry reg) =>
    t.isPlatform ? ['*.${reg.platformDomain}'] : t.linkHosts;

/// Expected `com.apple.developer.associated-domains` entitlement.
List<String> iosAssociatedDomainEntitlement(TenantManifest t, Registry reg) {
  final domains = iosAssociatedDomains(t, reg);
  return [
    for (final d in domains) 'applinks:$d',
    for (final d in domains) 'webcredentials:$d',
  ];
}

String _header(TenantManifest t) =>
    'GENERATED by tool/tenant_builder from tenants/${t.id}/tenant.json for an isolated '
    'iOS build workspace. Do not edit or commit.';

/// xcconfig values are raw to the end of the line; `//` starts a comment and
/// `$(` is a variable reference. The validator rejects both in identity values.
String _xc(String v) => v.trim();

String appIdentityXcconfig(TenantManifest t, Registry reg) {
  final domains = iosAssociatedDomains(t, reg);
  final b = StringBuffer()
    ..writeln('// ${_header(t)}')
    ..writeln('APP_BUNDLE_ID = ${_xc(t.bundleId ?? '')}')
    ..writeln('APP_DISPLAY_NAME = ${_xc(t.displayName)}')
    ..writeln(
      '// First Universal Links domain (all domains are listed in Runner.entitlements).',
    )
    ..writeln('APP_ASSOCIATED_DOMAIN = ${domains.isEmpty ? '' : domains.first}')
    ..writeln('APP_URL_SCHEME = ${_xc(t.iosScheme ?? '')}');
  if (t.teamId != null) b.writeln('DEVELOPMENT_TEAM = ${t.teamId}');
  return b.toString();
}

String tenantSigningXcconfig(TenantManifest t) =>
    '''
// ${_header(t)}
// Manual App Store signing with the tenant's own fastlane-match profile
// (installed by `fastlane ios match_readonly` before the build).
CODE_SIGN_STYLE = Manual
DEVELOPMENT_TEAM = ${t.teamId}
CODE_SIGN_IDENTITY = Apple Distribution
CODE_SIGN_IDENTITY[sdk=iphoneos*] = Apple Distribution
PROVISIONING_PROFILE_SPECIFIER = ${matchProfileName(t.bundleId!)}
''';

String releaseXcconfig(TenantManifest t) =>
    '''
// ${_header(t)}
#include "Generated.xcconfig"
#include "AppIdentity.xcconfig"
#include "TenantSigning.xcconfig"
''';

String entitlementsPlist(TenantManifest t, Registry reg) => encodeXmlPlist({
  if (t.pushEnabled) 'aps-environment': 'production',
  'com.apple.developer.associated-domains': iosAssociatedDomainEntitlement(
    t,
    reg,
  ),
}, comment: _header(t));

String exportOptionsPlist(TenantManifest t) => encodeXmlPlist({
  'destination': 'export',
  'manageAppVersionAndBuildNumber': false,
  'method': 'app-store-connect',
  'provisioningProfiles': {t.bundleId!: matchProfileName(t.bundleId!)},
  'signingCertificate': 'Apple Distribution',
  'signingStyle': 'manual',
  'stripSwiftSymbols': true,
  'teamID': t.teamId!,
  'uploadSymbols': true,
}, comment: _header(t));

String appIconContentsJson() {
  final images = [
    for (final (size, idiom, scale) in iosIconSlots)
      {
        'size': size,
        'idiom': idiom,
        'filename': _iconFile(size, scale),
        'scale': '${scale}x',
      },
  ];
  return '${const JsonEncoder.withIndent('  ').convert({
    'images': images,
    'info': {'version': 1, 'author': 'tool/tenant_builder'},
  })}\n';
}

/// Rendered icon files of the AppIcon set (relative to [iosAppIconSetDir]).
Map<String, List<int>> appIconSetFiles(File source) {
  final src = decodePngFile(source);
  final out = <String, List<int>>{
    'Contents.json': utf8.encode(appIconContentsJson()),
  };
  final cache = <int, List<int>>{};
  for (final (size, _, scale) in iosIconSlots) {
    final px = _iconPixels(size, scale);
    out[_iconFile(size, scale)] = cache[px] ??= resizePng(src, px);
  }
  return out;
}

/// Tenant Firebase iOS config (only used when push is enabled).
String iosFirebasePlistPath(TenantManifest t) =>
    p.join(t.dir, 'ios', 'GoogleService-Info.plist');

/// All overlay files for [t] (relative path -> bytes). Signing files are only
/// produced when the tenant has an Apple Team ID.
Map<String, List<int>> iosOverlayFiles(TenantManifest t, Registry reg) {
  final files = <String, List<int>>{
    'ios/Flutter/AppIdentity.xcconfig': utf8.encode(
      appIdentityXcconfig(t, reg),
    ),
    'ios/Runner/Runner.entitlements': utf8.encode(entitlementsPlist(t, reg)),
  };
  if (t.teamId != null && t.bundleId != null) {
    files['ios/Flutter/TenantSigning.xcconfig'] = utf8.encode(
      tenantSigningXcconfig(t),
    );
    files['ios/Flutter/Release.xcconfig'] = utf8.encode(releaseXcconfig(t));
    files['ExportOptions.plist'] = utf8.encode(exportOptionsPlist(t));
  }
  final icon = t.appIcon;
  if (icon != null) {
    appIconSetFiles(File(p.join(t.dir, icon))).forEach((name, bytes) {
      files['$iosAppIconSetDir/$name'] = bytes;
    });
  }
  if (t.pushEnabled) {
    final f = File(iosFirebasePlistPath(t));
    if (f.existsSync()) {
      files['ios/Runner/GoogleService-Info.plist'] = f.readAsBytesSync();
    }
  }
  return files;
}
