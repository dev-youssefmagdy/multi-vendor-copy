/// Launcher icon densities: legacy 48dp, adaptive foreground 108dp.
const _densities = {
  'mdpi': 1.0,
  'hdpi': 1.5,
  'xhdpi': 2.0,
  'xxhdpi': 3.0,
  'xxxhdpi': 4.0,
};
const markerFile = '.tenant_builder.json';

class AndroidTarget extends PlatformTarget {
  @override
  String get name => 'android';

  @override
  List<String> get artifactKinds => const ['aab', 'apk'];

  // ------------------------------------------------------------ generate --

  /// Files of `android/app/src/<id>/` (relative path -> bytes). Empty when the
  /// tenant needs no flavor overrides (e.g. `platform` keeps main/ icons).
  Map<String, List<int>> flavorFiles(TenantManifest t) {
    final files = <String, List<int>>{};
    final icon = t.appIcon;
    if (icon != null) {
      final src = decodePngFile(File(p.join(t.dir, icon)));
      for (final e in _densities.entries) {
        files['res/mipmap-${e.key}/ic_launcher.png'] = resizePng(
          src,
          (48 * e.value).round(),
        );
      }
      final fg = t.appIconForeground;
      if (fg != null) {
        final fgSrc = decodePngFile(File(p.join(t.dir, fg)));
        for (final e in _densities.entries) {
          files['res/drawable-${e.key}/ic_launcher_foreground.png'] = resizePng(
            fgSrc,
            (108 * e.value).round(),
          );
        }
        files['res/mipmap-anydpi-v26/ic_launcher.xml'] = utf8.encode(
          '''<?xml version="1.0" encoding="utf-8"?>
<!-- GENERATED by tool/tenant_builder from tenants/${t.id}/tenant.json. Do not edit. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background"/>
    <foreground android:drawable="@drawable/ic_launcher_foreground"/>
</adaptive-icon>
''',
        );
        files['res/values/tenant_launcher.xml'] = utf8.encode(
          '''<?xml version="1.0" encoding="utf-8"?>
<!-- GENERATED by tool/tenant_builder from tenants/${t.id}/tenant.json. Do not edit. -->
<resources>
    <color name="ic_launcher_background">${xmlEscape(t.adaptiveIconBackground.toUpperCase())}</color>
</resources>
''',
        );
      }
    }
    if (!t.isPlatform && t.extraLinkHosts.isNotEmpty) {
      final data = t.extraLinkHosts
          .map(
            (h) =>
                '                <data android:scheme="https" android:host="${xmlEscape(h)}"/>',
          )
          .join('\n');
      files['AndroidManifest.xml'] = utf8.encode(
        '''<?xml version="1.0" encoding="utf-8"?>
<!-- GENERATED by tool/tenant_builder from tenants/${t.id}/tenant.json. Do not edit.
     Extra verified App Links hosts (custom domains) of this store; the main host comes from the
     flavor's appLinkHost manifest placeholder (android/app/build.gradle.kts). -->
<manifest xmlns:android="http://schemas.android.com/apk/res/android">
    <application>
        <activity android:name=".MainActivity">
            <intent-filter android:autoVerify="true">
                <action android:name="android.intent.action.VIEW"/>
                <category android:name="android.intent.category.DEFAULT"/>
                <category android:name="android.intent.category.BROWSABLE"/>
$data
            </intent-filter>
        </activity>
    </application>
</manifest>
''',
      );
    }
    if (files.isNotEmpty) {
      files[markerFile] = utf8.encode(
        '{"generatedBy": "tool/tenant_builder", "tenant": "${t.id}", "source": "tenants/${t.id}/tenant.json"}\n',
      );
    }
    return files;
  }

  @override
  Future<GenerateResult> generate(
    ToolContext c,
    TenantManifest t, {
    bool check = false,
  }) async {
    final r = GenerateResult();
    final dir = c.ws.androidFlavorDir(t.id);
    final d = Directory(dir);
    if (d.existsSync() &&
        d.listSync().isNotEmpty &&
        !File(p.join(dir, markerFile)).existsSync()) {
      throw ToolException(
        '${c.ws.rel(dir)} exists but was not generated by tenant_builder; '
        'refusing to overwrite it. Move its contents into tenants/${t.id}/ and delete it.',
      );
    }
    final files = t.androidEnabled
        ? flavorFiles(t)
        : const <String, List<int>>{};
    FileSync(c.ws, check: check).syncTree(dir, files, r);
    if (!check &&
        files.isEmpty &&
        d.existsSync() &&
        d.listSync(recursive: true).whereType<File>().isEmpty) {
      d.deleteSync(recursive: true);
    }
    return r;
  }

  @override
  List<String> prune(ToolContext c, Set<String> keepIds, {bool check = false}) {
    final src = Directory(c.ws.path('android/app/src'));
    final removed = <String>[];
    if (!src.existsSync()) return removed;
    for (final d in src.listSync().whereType<Directory>()) {
      final id = p.basename(d.path);
      if (keepIds.contains(id)) continue;
      if (File(p.join(d.path, markerFile)).existsSync()) {
        removed.add(c.ws.rel(d.path));
        if (!check) d.deleteSync(recursive: true);
      }
    }
    return removed;
  }

  // ----------------------------------------------------------- run/build --

  List<String> _flavorArgs(ToolContext c, TenantManifest t) => [
    '--flavor',
    t.id,
    '-t',
    'lib/main.dart',
    '--dart-define-from-file=${c.ws.rel(c.ws.defineFile(t.id))}',
  ];

  @override
  Future<int> run(ToolContext c, TenantManifest t, List<String> flutterArgs) =>
      c.runner.run(c.flutter, [
        'run',
        ..._flavorArgs(c, t),
        ...flutterArgs,
      ], workingDirectory: c.ws.root);

  String flutterOutput(Workspace ws, String id, String artifact, String mode) =>
      artifact == 'aab'
      ? ws.path('build/app/outputs/bundle/$id${_cap(mode)}/app-$id-$mode.aab')
      : ws.path('build/app/outputs/flutter-apk/app-$id-$mode.apk');

  String distName(String id, AppVersion v, String artifact, String mode) =>
      '$id-${v.name}+${v.number}${mode == 'release' ? '' : '-$mode'}.$artifact';

  @override
  Future<BuildResult> build(ToolContext c, BuildRequest r) async {
    final t = r.tenant;
    final out = flutterOutput(c.ws, t.id, r.artifact, r.mode);
    if (!c.dryRun && File(out).existsSync()) File(out).deleteSync();
    final code = await c.runner.run(c.flutter, [
      'build',
      r.artifact == 'aab' ? 'appbundle' : 'apk',
      '--${r.mode}',
      ..._flavorArgs(c, t),
      '--build-name',
      r.version.name,
      '--build-number',
      '${r.version.number}',
      ...r.extraArgs,
    ], workingDirectory: c.ws.root);
    if (code != 0) {
      throw ToolException('flutter build failed for ${t.id} (exit $code)');
    }
    final distDir = c.ws.distDir(t.id, 'android');
    final dest = p.join(distDir, distName(t.id, r.version, r.artifact, r.mode));
    final infoPath = p.join(distDir, 'build-info.json');
    if (c.dryRun) {
      c.log.info(
        '[dry-run] copy ${c.ws.rel(out)} -> ${c.ws.rel(dest)}; write ${c.ws.rel(infoPath)}',
      );
      return BuildResult(dest, infoPath);
    }
    if (!File(out).existsSync()) {
      throw ToolException('build succeeded but ${c.ws.rel(out)} is missing');
    }
    Directory(distDir).createSync(recursive: true);
    File(out).copySync(dest);
    final git = await _git(c);
    final info = {
      'tenant': t.id,
      'platform': 'android',
      'artifact': p.basename(dest),
      'artifactType': r.artifact,
      'mode': r.mode,
      'applicationId': t.applicationId,
      'displayName': t.displayName,
      'storeHost': t.isPlatform ? null : t.storeHost,
      'versionName': r.version.name,
      'versionCode': r.version.number,
      'gitCommit': git.$1,
      'gitDirty': git.$2,
      'builtAtUtc': DateTime.now().toUtc().toIso8601String(),
      'sha256': sha256.convert(File(dest).readAsBytesSync()).toString(),
      'signing': r.mode == 'release' ? 'tenant upload key' : 'debug key',
    };
    File(infoPath).writeAsStringSync(
      '${const JsonEncoder.withIndent('  ').convert(info)}\n',
    );
    return BuildResult(dest, infoPath);
  }

  Future<(String?, bool)> _git(ToolContext c) async {
    try {
      final sha = await c.runner.capture('git', [
        'rev-parse',
        'HEAD',
      ], workingDirectory: c.ws.root);
      final st = await c.runner.capture('git', [
        'status',
        '--porcelain',
      ], workingDirectory: c.ws.root);
      return (
        sha.exitCode == 0 ? (sha.stdout as String).trim() : null,
        st.exitCode == 0 && (st.stdout as String).trim().isNotEmpty,
      );
    } catch (_) {
      return (null, false);
    }
  }

  // --------------------------------------------------------------- verify --

  /// Newest artifact of [t] in dist/ (from build-info.json).
  String? latestArtifact(Workspace ws, TenantManifest t) {
    final info = File(p.join(ws.distDir(t.id, 'android'), 'build-info.json'));
    if (!info.existsSync()) return null;
    final j = jsonDecode(info.readAsStringSync()) as Map<String, dynamic>;
    return p.join(ws.distDir(t.id, 'android'), j['artifact'] as String);
  }

  Map<String, dynamic>? _buildInfo(
    Workspace ws,
    TenantManifest t,
    String artifact,
  ) {
    final info = File(p.join(ws.distDir(t.id, 'android'), 'build-info.json'));
    if (!info.existsSync()) return null;
    final j = jsonDecode(info.readAsStringSync()) as Map<String, dynamic>;
    return j['artifact'] == p.basename(artifact) ? j : null;
  }

  @override
  Future<List<String>> verify(
    ToolContext c,
    Registry reg,
    TenantManifest t, {
    String? artifactPath,
  }) async {
    final problems = <String>[];
    final path = artifactPath ?? latestArtifact(c.ws, t);
    if (path == null || !File(path).existsSync()) {
      return [
        'no artifact found for ${t.id} (build it first or pass --artifact-path)',
      ];
    }
    c.log.info('Verifying ${c.ws.rel(path)}');
    final isAab = path.endsWith('.aab');
    final archive = ZipDecoder().decodeBytes(File(path).readAsBytesSync());
    final aapt2 = findAndroidTool(c, 'aapt2');

    // 1. identity from the compiled manifest + resources
    if (aapt2 == null) {
      c.log.warn(
        'aapt2 not found (set ANDROID_HOME); package/label/link checks skipped',
      );
    } else {
      final apkForAapt = isAab ? _protoApkFromBundle(archive) : path;
      try {
        final badging = await c.runner.capture(aapt2, [
          'dump',
          'badging',
          apkForAapt,
        ]);
        final xml = await c.runner.capture(aapt2, [
          'dump',
          'xmltree',
          '--file',
          'AndroidManifest.xml',
          apkForAapt,
        ]);
        if (badging.exitCode != 0) {
          problems.add('aapt2 dump badging failed: ${badging.stderr}');
        } else {
          problems.addAll(
            _checkBadging(c, t, '${badging.stdout}', _buildInfo(c.ws, t, path)),
          );
        }
        if (xml.exitCode == 0) {
          problems.addAll(_checkLinks(reg, t, '${xml.stdout}'));
        }
      } finally {
        if (isAab) File(apkForAapt).parent.deleteSync(recursive: true);
      }
    }

    // 2. icon + cross-tenant leak checks over the artifact contents
    problems.addAll(_checkContents(c, reg, t, archive, isAab));

    // 3. signing
    final mode =
        _buildInfo(c.ws, t, path)?['mode'] as String? ??
        (RegExp(r'-(debug|profile)\.(apk|aab)$').firstMatch(path)?.group(1) ??
            'release');
    problems.addAll(
      await _checkSigning(c, path, isAab, release: mode == 'release'),
    );
    return problems;
  }

  List<String> _checkBadging(
    ToolContext c,
    TenantManifest t,
    String out,
    Map<String, dynamic>? info,
  ) {
    final problems = <String>[];
    final pkg = RegExp(
      r"package: name='([^']*)' versionCode='([^']*)' versionName='([^']*)'",
    ).firstMatch(out);
    final label = RegExp(r"application-label:'([^']*)'")
        .firstMatch(out)
        ?.group(1);
    if (pkg == null) return ['could not read package from aapt2 output'];
    c.log.info(
      '  package ${pkg.group(1)}  version ${pkg.group(3)} (${pkg.group(2)})  label "$label"',
    );
    if (pkg.group(1) != t.applicationId) {
      problems.add('package is ${pkg.group(1)}, expected ${t.applicationId}');
    }
    if (label != t.displayName) {
      problems.add('app label is "$label", expected "${t.displayName}"');
    }
    if (info != null) {
      if ('${info['versionCode']}' != pkg.group(2)) {
        problems.add(
          'versionCode ${pkg.group(2)} != build-info ${info['versionCode']}',
        );
      }
      if ('${info['versionName']}' != pkg.group(3)) {
        problems.add(
          'versionName ${pkg.group(3)} != build-info ${info['versionName']}',
        );
      }
    }
    return problems;
  }

  List<String> _checkLinks(Registry reg, TenantManifest t, String xml) {
    final problems = <String>[];
    final hosts = RegExp(r':host\([^)]*\)="([^"]*)"')
        .allMatches(xml)
        .map((m) => m.group(1)!)
        .toSet();
    final schemes = RegExp(r':scheme\([^)]*\)="([^"]*)"')
        .allMatches(xml)
        .map((m) => m.group(1)!)
        .toSet();
    final expected = t.isPlatform
        ? {'*.${reg.platformDomain}'}
        : t.linkHosts.toSet();
    final wrong = hosts.difference(expected);
    final missing = expected.difference(hosts);
    if (wrong.isNotEmpty) {
      problems.add('App Links hosts not owned by ${t.id}: ${wrong.join(', ')}');
    }
    if (missing.isNotEmpty) {
      problems.add('App Links hosts missing: ${missing.join(', ')}');
    }
    if (!schemes.contains(t.androidScheme)) {
      problems.add('custom scheme ${t.androidScheme} not registered');
    }
    return problems;
  }

  /// aapt2 cannot read .aab; the bundle's base module is a "proto APK".
  String _protoApkFromBundle(Archive bundle) {
    final tmp = Directory.systemTemp.createTempSync('tenant_builder_aab');
    final out = Archive();
    for (final f in bundle.files) {
      if (!f.isFile || !f.name.startsWith('base/')) continue;
      var name = f.name.substring(5);
      if (name == 'manifest/AndroidManifest.xml') name = 'AndroidManifest.xml';
      if (name == 'resources.pb' ||
          name == 'AndroidManifest.xml' ||
          name.startsWith('res/')) {
        out.addFile(ArchiveFile.bytes(name, f.content));
      }
    }
    final path = p.join(tmp.path, 'base.apk');
    File(path).writeAsBytesSync(ZipEncoder().encode(out));
    return path;
  }

  /// Pixel hash of the tenant's mdpi launcher icon as it should appear in the
  /// artifact (generated icon, or main/ for tenants without their own icon).
  String? expectedIconHash(Workspace ws, TenantManifest t) {
    if (t.appIcon != null) {
      final src = File(p.join(t.dir, t.appIcon!));
      if (!src.existsSync()) return null;
      return pixelHashOfBytes(resizePng(decodePngFile(src), 48));
    }
    final main = File(
      p.join(ws.androidMainRes, 'mipmap-mdpi', 'ic_launcher.png'),
    );
    return main.existsSync() ? pixelHashOfBytes(main.readAsBytesSync()) : null;
  }

  List<String> _checkContents(
    ToolContext c,
    Registry reg,
    TenantManifest t,
    Archive archive,
    bool isAab,
  ) {
    final problems = <String>[];
    final iconHashes = <String>{};
    final resPrefix = isAab ? 'base/res/' : 'res/';
    for (final f in archive.files) {
      if (f.isFile &&
          f.name.startsWith(resPrefix) &&
          f.name.endsWith('.png') &&
          f.size < 1 << 20) {
        final h = pixelHashOfBytes(f.content);
        if (h != null) iconHashes.add(h);
      }
    }
    final mine = expectedIconHash(c.ws, t);
    if (mine == null) {
      c.log.warn('  cannot compute the expected icon for ${t.id}');
    } else if (!iconHashes.contains(mine)) {
      problems.add('launcher icon of ${t.id} not found in the artifact');
    } else {
      c.log.info('  launcher icon matches tenants/${t.id}');
    }

    // Other tenants' identity must not be inside this binary.
    final needles = <String, String>{};
    for (final o in reg.manifests.values) {
      if (o.id == t.id) continue;
      final otherIcon = expectedIconHash(c.ws, o);
      if (otherIcon != null &&
          otherIcon != mine &&
          iconHashes.contains(otherIcon)) {
        problems.add('contains the launcher icon of tenant ${o.id}');
      }
      for (final v in [o.applicationId, ...o.linkHosts]) {
        if (v != null &&
            v.isNotEmpty &&
            v != t.applicationId &&
            !t.linkHosts.contains(v)) {
          needles[v] = o.id;
        }
      }
    }
    final ownHost = t.isPlatform ? null : t.storeHost;
    var ownHostInDart = false;
    for (final f in archive.files) {
      if (!f.isFile) continue;
      final bytes = f.content;
      for (final n in needles.entries) {
        if (_contains(bytes, n.key)) {
          problems.add('${f.name} contains "${n.key}" of tenant ${n.value}');
        }
      }
      if (ownHost != null &&
          (f.name.endsWith('libapp.so') ||
              f.name.endsWith('kernel_blob.bin'))) {
        ownHostInDart = ownHostInDart || _contains(bytes, ownHost);
      }
    }
    if (ownHost != null) {
      if (ownHostInDart) {
        c.log.info('  Dart code is bound to $ownHost');
      } else {
        c.log.warn(
          '  could not find "$ownHost" in the Dart snapshot (TENANT_HOST binding not confirmed)',
        );
      }
    }
    return problems;
  }

  static bool _contains(List<int> hay, String needle) {
    final n = utf8.encode(needle);
    if (n.isEmpty || hay.length < n.length) return false;
    final first = n[0];
    outer:
    for (var i = 0; i <= hay.length - n.length; i++) {
      if (hay[i] != first) continue;
      for (var j = 1; j < n.length; j++) {
        if (hay[i + j] != n[j]) continue outer;
      }
      return true;
    }
    return false;
  }

  Future<List<String>> _checkSigning(
    ToolContext c,
    String path,
    bool isAab, {
    required bool release,
  }) async {
    String? out;
    if (isAab) {
      final keytool = _javaTool(c, 'keytool');
      if (keytool == null) {
        c.log.warn('keytool not found; signature not checked');
        return const [];
      }
      final r = await c.runner.capture(keytool, [
        '-printcert',
        '-jarfile',
        path,
      ]);
      out = '${r.stdout}${r.stderr}';
    } else {
      final apksigner = findAndroidTool(c, 'apksigner');
      if (apksigner == null) {
        c.log.warn('apksigner not found; signature not checked');
        return const [];
      }
      final r = await c.runner.capture(apksigner, [
        'verify',
        '--print-certs',
        path,
      ]);
      if (r.exitCode != 0) return ['signature does not verify: ${r.stderr}'];
      out = '${r.stdout}';
    }
    final owner = RegExp(r'(?:Owner|Signer #1 certificate DN): ([^\n]*)')
        .firstMatch(out)
        ?.group(1)
        ?.trim();
    if (owner == null) return release ? ['artifact is not signed'] : const [];
    c.log.info('  signed by: $owner');
    if (release && owner.contains('CN=Android Debug')) {
      return ['release artifact is signed with the Android DEBUG key'];
    }
    return const [];
  }

  String? sdkDir(ToolContext c) {
    for (final k in ['ANDROID_HOME', 'ANDROID_SDK_ROOT']) {
      final v = c.env[k];
      if (v != null && Directory(v).existsSync()) return v;
    }
    final lp = File(p.join(c.ws.androidDir, 'local.properties'));
    if (lp.existsSync()) {
      for (final line in lp.readAsLinesSync()) {
        if (line.startsWith('sdk.dir=')) return line.substring(8).trim();
      }
    }
    return null;
  }

  /// Newest build-tools binary ([name]) of the Android SDK.
  String? findAndroidTool(ToolContext c, String name) {
    final sdk = sdkDir(c);
    if (sdk == null) return null;
    final bt = Directory(p.join(sdk, 'build-tools'));
    if (!bt.existsSync()) return null;
    final versions =
        bt
            .listSync()
            .whereType<Directory>()
            .map((d) => p.basename(d.path))
            .toList()
          ..sort(_compareVersions);
    for (final v in versions.reversed) {
      final f = File(p.join(bt.path, v, name));
      if (f.existsSync()) return f.path;
    }
    return null;
  }

  String? _javaTool(ToolContext c, String name) {
    final home = c.env['JAVA_HOME'];
    if (home != null && File(p.join(home, 'bin', name)).existsSync()) {
      return p.join(home, 'bin', name);
    }
    for (final dir in (c.env['PATH'] ?? '').split(':')) {
      if (dir.isNotEmpty && File(p.join(dir, name)).existsSync()) {
        return p.join(dir, name);
      }
    }
    return null;
  }

  static int _compareVersions(String a, String b) {
    final x = a
        .split(RegExp(r'[.-]'))
        .map((s) => int.tryParse(s) ?? 0)
        .toList();
    final y = b
        .split(RegExp(r'[.-]'))
        .map((s) => int.tryParse(s) ?? 0)
        .toList();
    for (var i = 0; i < x.length && i < y.length; i++) {
      if (x[i] != y[i]) return x[i].compareTo(y[i]);
    }
    return x.length.compareTo(y.length);
  }

  // --------------------------------------------------------------- upload --

  static const allowedTracks = {'internal', 'alpha', 'beta'};

  @override
  Future<int> upload(
    ToolContext c,
    TenantManifest t, {
    required String track,
    required String releaseStatus,
    String? artifactPath,
  }) async {
    if (!allowedTracks.contains(track)) {
      throw ToolException(
        'track "$track" is not allowed. Uploads go to testing tracks only '
        '(${allowedTracks.join(', ')}); production is promoted by the tenant in Play Console.',
      );
    }
    if (releaseStatus != 'draft' && releaseStatus != 'completed') {
      throw ToolException('--release-status must be draft or completed');
    }
    final path = artifactPath ?? latestArtifact(c.ws, t);
    if (path == null ||
        !path.endsWith('.aab') ||
        (!c.dryRun && !File(path).existsSync())) {
      throw ToolException(
        'no release .aab for ${t.id}; run build --artifact aab --mode release first',
      );
    }
    final key = _playKey(c);
    return runLane(
      c,
      'android',
      'upload_testing',
      {
        'package_name': t.applicationId!,
        'track': track,
        'aab': p.isAbsolute(path) ? path : p.absolute(path),
        'release_status': releaseStatus,
      },
      environment: {'PLAY_SERVICE_ACCOUNT_JSON_PATH': key},
    );
  }

  String _playKey(ToolContext c) {
    final key = c.env['PLAY_SERVICE_ACCOUNT_JSON_PATH'];
    if (key == null || (!c.dryRun && !File(key).existsSync())) {
      throw ToolException(
        'PLAY_SERVICE_ACCOUNT_JSON_PATH must point to the tenant\'s Play service-account JSON',
      );
    }
    return key;
  }

