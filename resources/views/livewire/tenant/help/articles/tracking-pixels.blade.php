<h2>Pixel & Analytics Setup</h2>
<p>Connect marketing pixels to track visitors, add-to-carts, and purchases across Facebook, TikTok, Snapchat, and Google Analytics 4 — without touching any code.</p>

<h3>Where to enter your pixel IDs</h3>
<p>Go to <strong>Settings → Tracking</strong> and enter the ID for each platform you use.</p>

<h3>What gets tracked automatically</h3>
<ul>
    <li><strong>Page View</strong> — every page visit</li>
    <li><strong>View Content</strong> — when a customer opens a product page</li>
    <li><strong>Add to Cart</strong> — when a product is added to the cart</li>
    <li><strong>Initiate Checkout</strong> — when the customer enters the checkout</li>
    <li><strong>Purchase</strong> — when the order is confirmed (fires once per order)</li>
</ul>

<h3>How to find your pixel IDs</h3>
<ul>
    <li><strong>Facebook/Meta Pixel:</strong> Meta Business Suite → Events Manager → Your pixel → copy the 15–16 digit number</li>
    <li><strong>TikTok Pixel:</strong> TikTok Ads Manager → Assets → Events → Web Events → copy the pixel ID</li>
    <li><strong>Snapchat Pixel:</strong> Snapchat Ads Manager → Assets → Snap Pixel → copy the UUID</li>
    <li><strong>Google Analytics 4:</strong> GA4 property → Admin → Data Streams → your stream → Measurement ID (starts with <code>G-</code>)</li>
</ul>

<h3>Verifying pixels are firing</h3>
<ul>
    <li><strong>Meta:</strong> Install the Meta Pixel Helper Chrome extension and visit your storefront</li>
    <li><strong>TikTok:</strong> Install the TikTok Pixel Helper Chrome extension</li>
    <li><strong>GA4:</strong> Open GA4 → Reports → Realtime while visiting your storefront</li>
</ul>
