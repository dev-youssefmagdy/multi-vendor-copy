<h2>Getting Started</h2>
<p>Welcome to your store panel. Here's what to set up first.</p>

<div class="docs-step">
    <div class="docs-step-num">1</div>
    <div class="docs-step-body">
        <h3>Complete compliance verification</h3>
        <p>Go to <strong>Settings → Compliance</strong> and fill in your business, owner, and bank details. Upload required documents. Stores with incomplete compliance may have limited features.</p>
    </div>
</div>

<div class="docs-step">
    <div class="docs-step-num">2</div>
    <div class="docs-step-body">
        <h3>Set up your storefront appearance</h3>
        <p>Go to <strong>Store → Appearance</strong> to upload your logo, set banner images, choose a primary color, and activate a theme.</p>
    </div>
</div>

<div class="docs-step">
    <div class="docs-step-num">3</div>
    <div class="docs-step-body">
        <h3>Add products</h3>
        <p>Go to <strong>Products → My Products</strong> and click <strong>Add Product</strong>. Set a name, price, images, and variants.</p>
    </div>
</div>

<div class="docs-step">
    <div class="docs-step-num">4</div>
    <div class="docs-step-body">
        <h3>Configure shipping</h3>
        <p>Go to <strong>Shipping Management → Branches</strong> to create a branch with shipping zones and rates.</p>
    </div>
</div>

<div class="docs-step">
    <div class="docs-step-num">5</div>
    <div class="docs-step-body">
        <h3>Connect marketing pixels</h3>
        <p>Go to <strong>Settings → Tracking</strong> to add your Facebook, TikTok, Snapchat, or Google Analytics pixel IDs.</p>
    </div>
</div>

<div class="docs-step">
    <div class="docs-step-num">6</div>
    <div class="docs-step-body">
        <h3>Share your storefront URL</h3>
        <p>Your store is live at your domain or subdomain. Go to <strong>Domains</strong> to connect a custom domain.</p>
    </div>
</div>
