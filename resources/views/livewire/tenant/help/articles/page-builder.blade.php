<h2>Page Builder</h2>
<p>Reorder and show/hide sections on your storefront homepage — no code required.</p>

<h3>How to use it</h3>
<div class="docs-step">
    <div class="docs-step-num">1</div>
    <div class="docs-step-body">
        <h3>Open the Page Builder</h3>
        <p>Go to <strong>Store → Page Builder</strong> in your panel.</p>
    </div>
</div>
<div class="docs-step">
    <div class="docs-step-num">2</div>
    <div class="docs-step-body">
        <h3>Select your active theme</h3>
        <p>The theme selector shows your currently active theme. Each theme has its own section set.</p>
    </div>
</div>
<div class="docs-step">
    <div class="docs-step-num">3</div>
    <div class="docs-step-body">
        <h3>Drag sections to reorder</h3>
        <p>Drag any section up or down to change its position on the homepage. Click <strong>Save order</strong> to apply.</p>
    </div>
</div>
<div class="docs-step">
    <div class="docs-step-num">4</div>
    <div class="docs-step-body">
        <h3>Toggle visibility</h3>
        <p>Click the eye icon next to any section to show or hide it without removing it permanently.</p>
    </div>
</div>

<h3>Available sections per theme</h3>
<ul>
    <li><strong>Elora:</strong> Hero Banner, Trust Bar, Category Circles, Tabbed Products, Flash Sale Strip, Trending Now, Category Strip, Best Seller, New Arrivals, Shop by Category, Recommended For You</li>
    <li><strong>Souqify:</strong> Hero, Trust Bar, Trending This Week, Browse Categories, Today's Flash Sale, Top Products, Hero Banners, New Arrivals, Explore Products, Featured Products, Hot Deals, Special Offers, Top Rated, Recommended</li>
    <li><strong>Ecommet:</strong> Hero Banner, Trust Bar, Flash Deals, Category Pills + Grid, Flash Sale Strip, Best-Selling Items</li>
</ul>
