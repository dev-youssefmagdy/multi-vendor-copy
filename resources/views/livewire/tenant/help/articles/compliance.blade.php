<h2>Compliance & Verification</h2>
<p>Complete your compliance profile so we can verify your business and enable full store features, including payouts.</p>

<h3>Sections to fill in</h3>
<ul>
    <li><strong>Business</strong> — business name, store name, country, city, phone, and email</li>
    <li><strong>Owner</strong> — owner name, ID number, date of birth, and contact details</li>
    <li><strong>Company</strong> — company name, registration number, registration expiry, VAT number, and the registration document</li>
    <li><strong>Bank</strong> — bank name, account holder name, account number, IBAN, and currency (used for payouts)</li>
    <li><strong>Documents</strong> — national ID, commercial registration, tax certificate, and any additional supporting documents</li>
</ul>

<h3>How to complete your profile</h3>
<div class="docs-step">
    <div class="docs-step-num">1</div>
    <div class="docs-step-body">
        <h3>Open the Compliance Center</h3>
        <p>Go to <strong>Settings → Compliance</strong> in your panel.</p>
    </div>
</div>
<div class="docs-step">
    <div class="docs-step-num">2</div>
    <div class="docs-step-body">
        <h3>Fill in each section</h3>
        <p>Work through the Business, Owner, Company, Bank, and Documents sections. Each section saves independently.</p>
    </div>
</div>
<div class="docs-step">
    <div class="docs-step-num">3</div>
    <div class="docs-step-body">
        <h3>Upload your documents</h3>
        <p>Upload your national ID, commercial registration, and tax certificate (max 5MB each). You can add extra supporting documents if needed.</p>
    </div>
</div>
<div class="docs-step">
    <div class="docs-step-num">4</div>
    <div class="docs-step-body">
        <h3>Track your completion</h3>
        <p>Your completion percentage is shown in the panel navigation — keep filling in sections until it reaches 100%.</p>
    </div>
</div>

<h3>Why this matters</h3>
<p>Your bank details are used for payouts, and verified documents help us confirm your business is legitimate. Incomplete compliance may limit access to certain store features.</p>
