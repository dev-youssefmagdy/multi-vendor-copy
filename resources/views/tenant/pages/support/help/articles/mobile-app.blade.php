<h2>Mobile App</h2>
<p>Your store has a mobile app. Configure it under <strong>Store &rarr; Mobile App</strong> and pick its look under <strong>Store &rarr; App Themes</strong>.</p>
<h3>Settings</h3>
<ul>
    <li>App name, logo, splash image and optional color overrides</li>
    <li>Feature toggles and up to five bottom navigation items</li>
    <li>Support contacts and Google Play / App Store links</li>
    <li>Minimum app version (forces older apps to update) and maintenance mode</li>
</ul>
<h3>App themes</h3>
<p>The app uses the same designs as the built-in web themes (Ecommet, Elora, Souqify), but your choice is independent of the web storefront: the app and the website can use different variants. Until you pick one, the app follows your web theme. Custom uploaded themes are not available in the app.</p>
<h3>Deep links</h3>
<p>Customers open your store in the app with your store code or domain, shown at the top of the Mobile App page.</p>
