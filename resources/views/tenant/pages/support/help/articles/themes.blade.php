<h2>Themes & Appearance</h2>
<p>Your storefront can use one of the built-in themes or a custom uploaded template. Themes control the entire look — layout, colors, fonts, and page structure.</p>

<h3>Built-in themes</h3>
<ul>
    <li><strong>Elora</strong> — Warm, fashion-forward design with large hero images and product carousels</li>
    <li><strong>Souqify</strong> — Arabic/Middle-East optimized marketplace layout with rich category navigation</li>
    <li><strong>Ecommet</strong> — Clean, minimal e-commerce design focused on conversion</li>
</ul>

<h3>How to switch themes</h3>
<div class="docs-step">
    <div class="docs-step-num">1</div>
    <div class="docs-step-body">
        <h3>Go to Appearance</h3>
        <p>Navigate to <strong>Store → Appearance</strong> in your panel.</p>
    </div>
</div>
<div class="docs-step">
    <div class="docs-step-num">2</div>
    <div class="docs-step-body">
        <h3>Select a theme</h3>
        <p>Browse the available themes. Click <strong>Preview</strong> to see it on your storefront before activating.</p>
    </div>
</div>
<div class="docs-step">
    <div class="docs-step-num">3</div>
    <div class="docs-step-body">
        <h3>Activate</h3>
        <p>Click <strong>Activate</strong> next to the theme you want. Your storefront updates instantly.</p>
    </div>
</div>

<h3>Customizing your theme</h3>
<ul>
    <li><strong>Logo:</strong> Store → Appearance → Logo tab</li>
    <li><strong>Banner images:</strong> Store → Appearance → Banners tab</li>
    <li><strong>Colors:</strong> Store → Appearance → General tab (primary color picker)</li>
    <li><strong>Homepage layout:</strong> Store → Page Builder</li>
    <li><strong>Custom HTML template:</strong> Store → Custom Template</li>
</ul>
